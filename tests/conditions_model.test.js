"use strict";
const assert=require("node:assert/strict"),m=require("../static/conditions-model.js");
const now=Date.parse("2026-11-14T22:00:00Z"),position={lat:44.95,lon:-93.4};
const row=(station,lat,tempF=40,extra={})=>({station,name:station,lat,lon:-93.4,tempF,dewpointF:25,kind:"reference",time:"2026-11-14T21:55:00Z",wind:{speedMph:10,direction:350},...extra});
const stations=[row("A",44.96),row("B",44.98),row("C",45.0),row("D",45.02,55)];
let r=m.estimate(stations,position,now);
assert.equal(r.available,true);assert.equal(r.tempF,40,"A single hot station cannot pull the estimate upward");
assert.equal(m.estimate([row("HOT",44.9501,55),row("COOL1",45.15),row("COOL2",45.2)],position,now).tempF,40,"A very close station cannot hold a majority vote");
assert.equal(m.estimate(stations.slice(0,2),position,now).available,false);
assert.equal(m.estimate(stations.map(row=>({...row,time:"2026-11-14T21:00:00Z"})),position,now).available,false);
assert.equal(m.estimate(stations.map(row=>({...row,kind:"community"})),position,now).available,false);
assert.equal(m.estimate([stations[0],{...stations[0],station:"duplicate"},stations[1]],position,now).available,false);
assert.equal(m.estimate([stations[0],stations[1],{...stations[2],time:"2026-11-14T22:01:00Z"}],position,now).available,false);
r=m.estimate([row("N",44.96,40,{wind:{speedMph:10,direction:350}}),row("N2",44.98,40,{wind:{speedMph:10,direction:10}}),row("N3",45,40,{wind:{speedMph:10,direction:0}})],position,now);
assert.ok(r.wind.direction<10||r.wind.direction>350);
assert.ok(Math.abs(r.wind.speedMph-10)<1e-10);
assert.equal(m.estimate(stations.map(row=>({...row,dewpointF:null})),position,now).dewpointF,null);
assert.equal(m.estimate(stations,{lat:43,lon:-89},now).available,false);
assert.equal(m.estimate(stations,{lat:NaN,lon:-89},now).available,false);
console.log("Conditions model checks passed: coverage, ages, duplicate sites, robust temperature and wind vectors.");
